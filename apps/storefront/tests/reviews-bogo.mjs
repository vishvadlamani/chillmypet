import assert from 'node:assert/strict';
import { chromium } from 'playwright';

const base = process.env.BASE_URL ?? 'http://127.0.0.1:5173';
const browser = await chromium.launch({ executablePath: process.env.CHROMIUM_PATH || undefined });
const context = await browser.newContext({ viewport: { width: 390, height: 664 } });
await context.route('**/connect.facebook.net/**', (route) => route.abort());
await context.route('**/facebook.com/**', (route) => route.abort());
await context.route('**/googletagmanager.com/**', (route) => route.abort());
await context.route('**/google-analytics.com/**', (route) => route.abort());
await context.route('**/api/track', (route) => route.fulfill({ status: 204 }));
const page = await context.newPage();
const errors = [];
page.on('pageerror', (error) => errors.push(error.message));
try {
	await page.goto(`${base}/products/christmas-tree-costume`, { waitUntil: 'networkidle' });
	assert.match(await page.locator('.tree-strip').innerText(), /BUY ONE, GET ONE FREE[\s\S]*Christmas Tree Costume/i);
	assert.equal(await page.locator('#variant-picker .tier').count(), 0);
	assert.equal(await page.locator('#size-picker input:checked').count(), 0);
	assert.ok(await page.locator('#size-picker label').first().evaluate((element) => element.getBoundingClientRect().bottom <= 664));
	assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
	await page.locator('#size-picker label').filter({ hasText: /^\s*M\s*$/ }).click();
	await page.getByRole('button', { name: /Get two costumes/ }).click();
	await page.waitForURL('**/products/christmas-tree-costume/checkout');
	await page.locator('.classic-totals .total').filter({ hasText: '$27.99' }).waitFor();
	assert.match(await page.locator('.classic-totals').innerText(), /Buy one, get one free/);
	const lines = await page.evaluate(() => JSON.parse(localStorage.getItem('chillmypet.cart.v1')));
	assert.equal(lines[0].quantity, 2);
	assert.equal(lines[0].colour, 'green');
	assert.equal(lines[0].size, 'M');
	await page.getByRole('button', { name: 'Change', exact: true }).first().click();
	await page.selectOption('#order-qty', '3');
	await page.locator('.classic-totals .total').filter({ hasText: '$55.98' }).waitFor();
	await page.selectOption('#order-qty', '1');
	await page.locator('.classic-totals .total').filter({ hasText: '$27.99' }).waitFor();
	assert.doesNotMatch(await page.locator('.classic-totals').innerText(), /Buy one, get one free/);
	console.log('PASS  Mobile offer, first-screen size controls, two-unit handoff, odd quantities and removal of free item');

	await page.goto(`${base}/products/christmas-tree-costume#write-review`, { waitUntil: 'networkidle' });
	const author = `Review check ${Date.now()}`;
	const body = 'A useful review with <script>literal text</script> that must be escaped.';
	const reviewForm = page.locator('form[action="?/review"]');
	await reviewForm.locator('[name="author"]').fill(author);
	await reviewForm.locator('[name="rating"]').selectOption('1');
	await reviewForm.locator('[name="body"]').fill(body);
	await reviewForm.getByRole('button', { name: 'Submit review' }).click();
	await page.getByRole('status').filter({ hasText: 'will appear after approval' }).waitFor();
	await page.reload({ waitUntil: 'networkidle' });
	assert.equal(await page.locator('.review-list article', { hasText: author }).count(), 0);
	const denied = await page.request.get(`${base}/admin/reviews`);
	assert.equal(denied.status(), 401);
	const admin = await browser.newContext({ httpCredentials: { username: 'admin', password: process.env.ADMIN_PASSWORD ?? 'local-review-check' } });
	const adminPage = await admin.newPage();
	await adminPage.goto(`${base}/admin/reviews`, { waitUntil: 'networkidle' });
	const pending = adminPage.locator('article', { hasText: author });
	await pending.getByRole('button', { name: 'Publish review' }).click();
	await pending.waitFor({ state: 'detached' });
	await page.reload({ waitUntil: 'networkidle' });
	const published = page.locator('.review-list article', { hasText: author });
	assert.equal(await published.count(), 1);
	assert.equal(await published.locator('.review-body').innerText(), body);
	assert.equal(await published.locator('script').count(), 0);
	assert.equal(await published.locator('.stars').getAttribute('aria-label'), '1 / 5');
	await page.goto(`${base}/products/christmas-hoodie`, { waitUntil: 'networkidle' });
	assert.equal(await page.locator('.review-list article', { hasText: author }).count(), 0);
	assert.equal(await page.locator('#variant-picker .tier').count(), 3);
	await adminPage.goto(`${base}/admin/reviews?status=published`, { waitUntil: 'networkidle' });
	await adminPage.locator('article', { hasText: author }).getByRole('button', { name: 'Hide review' }).click();
	await adminPage.locator('article', { hasText: author }).waitFor({ state: 'detached' });
	await page.goto(`${base}/products/christmas-tree-costume`, { waitUntil: 'networkidle' });
	assert.equal(await page.locator('.review-list article', { hasText: author }).count(), 0);
	await admin.close();
	assert.deepEqual(errors, []);
	console.log('PASS  Review submission, authenticated approval, one-star publication, escaping, product isolation and hiding');
} finally {
	await browser.close();
}
